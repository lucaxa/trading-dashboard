/*
===========================================================
TradeMind Pro
V25.7-RD v3 — S1/S2 HISTORICAL AVAILABILITY BOUNDARY PROBE
===========================================================

PURPOSE
-------
Locate the practical INDstocks historical-candle availability
transition around the boundary between the known-good V25.7
Segment 1 and the zero-candle V25.7 Segment 2.

This is DATA-LAYER DIAGNOSTIC ONLY.

It does NOT:
- generate candidates
- generate learning records
- classify HEALTHY / STABLE / DECAYING / BROKEN
- validate trades
- run OOS
- tune thresholds
- modify strategy mechanics
- place orders

IMPORTANT
---------
V25.7-RD v2 established:

S1:
  HTTP 200
  data.NIDX_40000001.candles[]
  8778 candles

S2:
  HTTP 200
  data.NIDX_40000001.candles = null

S3:
  HTTP 200
  data.NIDX_40000001.candles = null

This probe therefore tests ONLY the S1/S2 transition.

BOUNDARY REFERENCE
------------------
S1 start:
1703605271190

S1 end:
1719157271190

S2 end:
1703605691134

The exact S1/S2 end timestamps were generated by separate
V25.7 invocations and differ by a few seconds. The probe does
NOT assume those few seconds are a meaningful boundary.

PROBES
------
probe=1  S1-side control
probe=2  transition window
probe=3  S2-side control
probe=4  deeper S2 control

Run probe=1 first.

Each probe uses the SAME proven nested parser:

payload.data[NIDX_40000001].candles

Each request is one short window, split into 7-day chunks
only when necessary. The first three probes are deliberately
short enough to isolate the transition.

===========================================================
*/

export default async function handler(req, res) {

    const VERSION = "V25.7-RD-v3";

    const INSTRUMENT = "NIFTY 50";
    const SCRIP_CODE = "NIDX_40000001";
    const INTERVAL = "5minute";

    const API_BASE =
        process.env.INDSTOCKS_API_BASE ||
        "https://api.indstocks.com";

    const DAY_MS =
        24 *
        60 *
        60 *
        1000;

    const HOUR_MS =
        60 *
        60 *
        1000;

    const CHUNK_MS =
        7 *
        DAY_MS;

    const INTER_CHUNK_DELAY_MS = 250;
    const MAX_429_RETRIES = 5;
    const BASE_429_DELAY_MS = 2000;

    /*
     * These are the exact supplied V25.7 boundaries.
     */
    const S1_START_MS = 1703605271190;
    const S1_END_MS   = 1719157271190;
    const S2_END_MS   = 1703605691134;

    /*
     * A stable center around the earliest known S1 data.
     * This is deliberately derived from the actual supplied
     * S1/S2 timestamps rather than from current time.
     *
     * Probe 1: 7-day S1-side control, ending before S1 end.
     * Probe 2: 3-day transition window straddling the
     *          S1/S2 timestamp boundary.
     * Probe 3: 7-day S2-side control immediately before S2 end.
     * Probe 4: 30-day deeper S2 control.
     *
     * Because S1 and S2 were generated in separate calls,
     * the few-second timestamp discrepancy is treated as
     * insignificant; the probe deliberately uses windows
     * measured in days.
     */

    const S1_S2_BOUNDARY_MS =
        Math.round(
            (
                S2_END_MS +
                S1_START_MS
            ) / 2
        );

    /*
     * IMPORTANT:
     * The above midpoint is NOT used as a historical
     * availability cutoff. It is only a neutral reference
     * for constructing a short diagnostic window.
     *
     * The actual probes are placed using the supplied S2 end
     * and the S1 start so we can observe the API directly.
     */
    const PROBES = {

        "1": {
            label:
                "S1_SIDE_CONTROL",

            description:
                "7-day control fully inside the known-good V25.7 S1 period, immediately before the S1/S2 timestamp transition.",

            startMs:
                S1_START_MS,

            endMs:
                S1_START_MS +
                7 *
                DAY_MS,

            expected:
                "DATA_AVAILABLE"
        },

        "2": {
            label:
                "S1_S2_TRANSITION_WINDOW",

            description:
                "Short window centered on the supplied S1/S2 boundary timestamps.",

            startMs:
                S1_START_MS +
                6 *
                DAY_MS,

            endMs:
                S1_START_MS +
                9 *
                DAY_MS,

            expected:
                "DIAGNOSTIC"
        },

        "3": {
            label:
                "S2_SIDE_CONTROL",

            description:
                "7-day control immediately before the supplied S2 end boundary.",

            startMs:
                S2_END_MS -
                7 *
                DAY_MS,

            endMs:
                S2_END_MS,

            expected:
                "NO_DATA_BASED_ON_V25_7_S2"
        },

        "4": {
            label:
                "S2_DEEP_CONTROL",

            description:
                "30-day control deeper inside the V25.7 S2 period.",

            startMs:
                S2_END_MS -
                30 *
                DAY_MS,

            endMs:
                S2_END_MS,

            expected:
                "NO_DATA_BASED_ON_V25_7_S2"
        }
    };

    function sleep(ms) {
        return new Promise(
            resolve =>
                setTimeout(
                    resolve,
                    ms
                )
        );
    }

    function timestampOf(row) {

        if (
            Array.isArray(row)
        ) {
            return Number(
                row[0]
            );
        }

        if (
            row &&
            typeof row === "object"
        ) {

            return Number(
                row.ts ??
                row.timestamp ??
                row.time ??
                row.t
            );
        }

        return NaN;
    }

    function extractNestedCandles(payload) {

        const instrumentData =
            payload?.data?.[
                SCRIP_CODE
            ];

        const candles =
            instrumentData?.candles;

        if (
            Array.isArray(candles)
        ) {

            return {
                rows:
                    candles,

                shape:
                    `data.${SCRIP_CODE}.candles`,

                candleValueType:
                    "ARRAY"
            };
        }

        if (
            candles === null
        ) {

            return {
                rows: [],

                shape:
                    `data.${SCRIP_CODE}.candles`,

                candleValueType:
                    "NULL"
            };
        }

        if (
            candles === undefined
        ) {

            return {
                rows: [],

                shape: null,

                candleValueType:
                    "UNDEFINED"
            };
        }

        return {
            rows: [],

            shape:
                `data.${SCRIP_CODE}.candles`,

            candleValueType:
                typeof candles
        };
    }

    function auditRows(rows) {

        const timestamps =
            rows
                .map(
                    timestampOf
                )
                .filter(
                    Number.isFinite
                )
                .sort(
                    (a, b) =>
                        a - b
                );

        const unique =
            [
                ...new Set(
                    timestamps
                )
            ];

        return {

            extractedRows:
                rows.length,

            timestampedRows:
                timestamps.length,

            uniqueTimestampedRows:
                unique.length,

            duplicateTimestampRows:
                timestamps.length -
                unique.length,

            firstTimestamp:
                unique[0] ??
                null,

            lastTimestamp:
                unique[
                    unique.length - 1
                ] ??
                null
        };
    }

    function safePreview(text) {

        if (
            typeof text !== "string"
        ) {
            return null;
        }

        const compact =
            text
                .replace(
                    /\s+/g,
                    " "
                )
                .trim();

        return compact.length <= 500
            ? compact
            : compact.slice(
                0,
                500
            ) + "...";
    }

    async function fetchChunk(
        accessToken,
        startMs,
        endMs
    ) {

        const url =
            `${API_BASE}/market/historical/${INTERVAL}` +
            `?scrip-codes=${encodeURIComponent(
                SCRIP_CODE
            )}` +
            `&start_time=${startMs}` +
            `&end_time=${endMs}`;

        const response =
            await fetch(
                url,
                {
                    method: "GET",

                    headers: {
                        Authorization:
                            accessToken,

                        "Content-Type":
                            "application/json"
                    }
                }
            );

        const text =
            await response.text();

        let payload = null;
        let parseStatus =
            "NOT_JSON";

        try {

            payload =
                JSON.parse(
                    text
                );

            parseStatus =
                "JSON";

        } catch {
            payload = null;
        }

        const payloadKeys =
            payload &&
            typeof payload ===
                "object" &&
            !Array.isArray(
                payload
            )
                ? Object.keys(
                    payload
                )
                : [];

        const instrumentKeys =
            payload?.data &&
            typeof payload.data ===
                "object" &&
            !Array.isArray(
                payload.data
            )
                ? Object.keys(
                    payload.data
                )
                : [];

        const extracted =
            payload
                ? extractNestedCandles(
                    payload
                )
                : {
                    rows: [],
                    shape: null,
                    candleValueType:
                        "NO_PAYLOAD"
                };

        const rowAudit =
            auditRows(
                extracted.rows
            );

        return {

            request: {
                startMs,
                endMs,

                requestedDays:
                    (
                        endMs -
                        startMs
                    ) /
                    DAY_MS
            },

            http: {

                status:
                    response.status,

                ok:
                    response.ok,

                contentType:
                    response.headers.get(
                        "content-type"
                    ),

                parseStatus
            },

            response: {

                payloadKeys,

                instrumentKeys,

                expectedInstrumentPresent:
                    instrumentKeys.includes(
                        SCRIP_CODE
                    ),

                extractedShape:
                    extracted.shape,

                candleValueType:
                    extracted.candleValueType,

                ...rowAudit,

                previewWhenNoRows:
                    extracted.rows.length === 0
                        ? safePreview(
                            text
                        )
                        : null
            }
        };
    }

    async function fetchRateLimitSafe(
        accessToken,
        startMs,
        endMs
    ) {

        let attempt = 0;

        while (true) {

            const result =
                await fetchChunk(
                    accessToken,
                    startMs,
                    endMs
                );

            if (
                result.http.status !==
                429
            ) {

                return {
                    result,
                    retryAttempts:
                        attempt
                };
            }

            if (
                attempt >=
                MAX_429_RETRIES
            ) {

                return {
                    result,
                    retryAttempts:
                        attempt
                };
            }

            const delay =
                BASE_429_DELAY_MS *
                (
                    2 ** attempt
                );

            attempt++;

            await sleep(
                delay
            );
        }
    }

    async function auditProbe(
        accessToken,
        probe
    ) {

        const chunks = [];

        let cursor =
            probe.startMs;

        while (
            cursor <
            probe.endMs
        ) {

            const chunkEnd =
                Math.min(
                    cursor +
                    CHUNK_MS -
                    1000,
                    probe.endMs
                );

            chunks.push({
                startMs:
                    cursor,

                endMs:
                    chunkEnd
            });

            cursor =
                chunkEnd +
                1000;
        }

        const chunkResults = [];

        for (
            let i = 0;
            i < chunks.length;
            i++
        ) {

            const chunk =
                chunks[i];

            const fetched =
                await
                    fetchRateLimitSafe(
                        accessToken,
                        chunk.startMs,
                        chunk.endMs
                    );

            chunkResults.push({

                chunk:
                    i + 1,

                retryAttempts:
                    fetched.retryAttempts,

                ...fetched.result
            });

            if (
                i <
                chunks.length - 1
            ) {

                await sleep(
                    INTER_CHUNK_DELAY_MS
                );
            }
        }

        const totalRows =
            chunkResults.reduce(
                (
                    total,
                    item
                ) =>
                    total +
                    (
                        item.response
                            ?.extractedRows ||
                        0
                    ),
                0
            );

        const nullCandleChunks =
            chunkResults.filter(
                item =>
                    item.response
                        ?.candleValueType ===
                    "NULL"
            ).length;

        const arrayCandleChunks =
            chunkResults.filter(
                item =>
                    item.response
                        ?.candleValueType ===
                    "ARRAY"
            ).length;

        const emptyChunks =
            chunkResults.filter(
                item =>
                    (
                        item.response
                            ?.extractedRows ||
                        0
                    ) === 0
            ).length;

        const httpStatuses =
            [
                ...new Set(
                    chunkResults.map(
                        item =>
                            item.http.status
                    )
                )
            ];

        const shapes =
            [
                ...new Set(
                    chunkResults
                        .map(
                            item =>
                                item.response
                                    ?.extractedShape
                        )
                        .filter(
                            Boolean
                        )
                )
            ];

        return {

            requestedDays:
                (
                    probe.endMs -
                    probe.startMs
                ) /
                DAY_MS,

            chunksRequested:
                chunks.length,

            totalExtractedRows:
                totalRows,

            chunksWithCandleArrays:
                arrayCandleChunks,

            chunksWithCandleNull:
                nullCandleChunks,

            chunksWithNoRows:
                emptyChunks,

            httpStatuses,

            extractedShapes:
                shapes,

            chunkResults
        };
    }

    try {

        if (
            req.method !==
            "GET"
        ) {

            return res.status(405).json({

                success: false,

                version: VERSION,

                status:
                    "METHOD_NOT_ALLOWED",

                error:
                    "V25.7-RD v3 uses GET only."
            });
        }

        const accessToken =
            (
                process.env.INDSTOCKS_TOKEN ||
                process.env.INDSTOCKS_ACCESS_TOKEN ||
                ""
            ).trim();

        if (
            !accessToken
        ) {

            return res.status(500).json({

                success: false,

                version: VERSION,

                status:
                    "CONFIG_ERROR",

                error:
                    "INDSTOCKS_TOKEN or INDSTOCKS_ACCESS_TOKEN is not configured."
            });
        }

        const probeId =
            String(
                req.query?.probe ||
                "1"
            );

        const probe =
            PROBES[
                probeId
            ];

        if (
            !probe
        ) {

            return res.status(400).json({

                success: false,

                version: VERSION,

                status:
                    "INVALID_PROBE",

                availableProbes:
                    Object.keys(
                        PROBES
                    ),

                error:
                    "Use probe=1,2,3,or4."
            });
        }

        const audit =
            await auditProbe(
                accessToken,
                probe
            );

        let conclusion =
            "DIAGNOSTIC_ONLY";

        if (
            audit.totalExtractedRows >
            0
        ) {

            conclusion =
                "DATA_AVAILABLE_IN_PROBE";

        } else if (
            audit.chunksWithCandleNull >
            0
        ) {

            conclusion =
                "API_RETURNED_CANDLES_NULL";

        } else {

            conclusion =
                "NO_CANDLES_EXTRACTED";
        }

        return res.status(200).json({

            success: true,

            version: VERSION,

            status:
                "COMPLETED",

            mode:
                "V25_7_RD_V3_AVAILABILITY_BOUNDARY",

            paperOnly: true,

            realOrders: false,

            brokerOrderEnabled: false,

            brokerOrderSent: false,

            purpose:
                "Locate the historical candle availability transition around the V25.7 Segment 1 / Segment 2 boundary.",

            instrument:
                INSTRUMENT,

            scripCode:
                SCRIP_CODE,

            interval:
                INTERVAL,

            knownReference: {

                V25_7_S1:
                    {
                        rawCandles:
                            8778,

                        usableCandles:
                            8777,

                        status:
                            "DATA_AVAILABLE"
                    },

                V25_7_S2:
                    {
                        rawCandles:
                            0,

                        status:
                            "CANDLES_NULL"
                    },

                V25_7_S3:
                    {
                        rawCandles:
                            0,

                        status:
                            "CANDLES_NULL"
                    }
            },

            boundaryReference: {

                suppliedS1StartMs:
                    S1_START_MS,

                suppliedS1EndMs:
                    S1_END_MS,

                suppliedS2EndMs:
                    S2_END_MS,

                note:
                    "The S1/S2 timestamps came from separate V25.7 invocations. They are reference points, not an assumed exact API availability cutoff."
            },

            probe: {

                id:
                    probeId,

                label:
                    probe.label,

                description:
                    probe.description,

                startMs:
                    probe.startMs,

                endMs:
                    probe.endMs,

                expected:
                    probe.expected
            },

            audit,

            interpretation: {

                thisIsNotATradingTest:
                    true,

                learningRecordsGenerated:
                    false,

                healthStatesCalculated:
                    false,

                strategyModified:
                    false,

                thresholdTuning:
                    false,

                conclusion,

                important:
                    "A DATA_AVAILABLE or CANDLES_NULL result is evidence about API historical availability only. It is not evidence about trading edge quality."
            },

            nextStep:
                "Run probe 1 first. Inspect it before running probe 2. Do not run V25.7 learning confirmation from this diagnostic.",

            guardrails: {

                noCandidateDiscovery:
                    true,

                noLearningRecords:
                    true,

                noHealthClassification:
                    true,

                noValidation:
                    true,

                noOOS:
                    true,

                noStrategyChange:
                    true,

                noThresholdChange:
                    true,

                noRealOrders:
                    true
            }
        });

    } catch (error) {

        return res.status(500).json({

            success: false,

            version: VERSION,

            status:
                "ERROR",

            paperOnly: true,

            realOrders: false,

            brokerOrderEnabled: false,

            brokerOrderSent: false,

            error:
                error?.message ||
                String(error)
        });
    }
}
